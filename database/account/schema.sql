-- Account owner: users and pets in the shared pawinn database.
BEGIN;

CREATE TABLE IF NOT EXISTS users (
    user_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(80) NOT NULL CHECK (length(trim(full_name)) > 0),
    email VARCHAR(254) NOT NULL CHECK (length(trim(email)) > 0),
    password_hash VARCHAR(255) NOT NULL,
    phone VARCHAR(30),
    role VARCHAR(10) NOT NULL DEFAULT 'CUSTOMER'
        CONSTRAINT users_account_role_check CHECK (role IN ('CUSTOMER', 'STAFF', 'ADMIN')),
    account_status VARCHAR(10) NOT NULL DEFAULT 'ACTIVE'
        CONSTRAINT users_account_status_check CHECK (account_status IN ('ACTIVE', 'SUSPENDED')),
    session_version INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS users_email_unique ON users (lower(email));

CREATE TABLE IF NOT EXISTS account_audit (
    audit_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id INTEGER NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
    target_id INTEGER NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
    action VARCHAR(25) NOT NULL CHECK (action IN (
        'ADMIN_BOOTSTRAPPED', 'STAFF_CREATED', 'STAFF_GRANTED', 'STAFF_REVOKED',
        'ACCOUNT_SUSPENDED', 'ACCOUNT_REACTIVATED'
    )),
    details JSONB NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);

CREATE INDEX IF NOT EXISTS account_audit_target_history ON account_audit (target_id, audit_id DESC);

CREATE TABLE IF NOT EXISTS pets (
    pet_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id INTEGER NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
    name VARCHAR(40) NOT NULL CHECK (length(trim(name)) > 0),
    species VARCHAR(10) NOT NULL CHECK (species IN ('Dog', 'Cat')),
    breed VARCHAR(80),
    birth_date DATE CHECK (birth_date <= CURRENT_DATE),
    care_notes TEXT,
    -- Lets a booking FK verify that pet_id belongs to its user_id.
    UNIQUE (pet_id, owner_id)
);

COMMIT;
