-- Add booking instructions and the private update feed to existing PawInn databases.
ALTER TABLE bookings ADD COLUMN IF NOT EXISTS special_care VARCHAR(2000) NOT NULL DEFAULT '';

CREATE TABLE IF NOT EXISTS pet_updates (
    pet_update_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id INTEGER NOT NULL REFERENCES bookings(booking_id) ON DELETE RESTRICT,
    staff_user_id INTEGER NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
    message VARCHAR(2000) NOT NULL DEFAULT '',
    photo BYTEA,
    photo_type TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (length(trim(message)) > 0 OR photo IS NOT NULL),
    CHECK (
        (photo IS NULL AND photo_type IS NULL)
        OR (photo IS NOT NULL AND photo_type IS NOT NULL
            AND photo_type IN ('image/jpeg', 'image/png', 'image/webp')
            AND octet_length(photo) BETWEEN 1 AND 2097152)
    )
);

CREATE INDEX IF NOT EXISTS pet_updates_booking_idx ON pet_updates (booking_id, pet_update_id DESC);
