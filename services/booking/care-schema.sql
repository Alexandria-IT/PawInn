-- Booking applies this additive migration on startup.
CREATE TABLE IF NOT EXISTS booking_care_reports (
    report_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id INTEGER NOT NULL REFERENCES bookings(booking_id) ON DELETE RESTRICT,
    care_date DATE NOT NULL,
    message TEXT NOT NULL CHECK (length(trim(message)) BETWEEN 1 AND 2000),
    staff_user_id INTEGER NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (booking_id, care_date)
);

CREATE TABLE IF NOT EXISTS booking_care_photos (
    photo_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_id INTEGER NOT NULL REFERENCES booking_care_reports(report_id) ON DELETE RESTRICT,
    content BYTEA NOT NULL CHECK (octet_length(content) BETWEEN 1 AND 2097152),
    content_type TEXT NOT NULL CHECK (content_type IN ('image/jpeg', 'image/png', 'image/webp')),
    is_current BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE INDEX IF NOT EXISTS booking_care_photos_current
    ON booking_care_photos (report_id, photo_id) WHERE is_current;

CREATE TABLE IF NOT EXISTS booking_care_events (
    event_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id INTEGER NOT NULL REFERENCES bookings(booking_id) ON DELETE RESTRICT,
    care_date DATE NOT NULL,
    event_time TIME(0) NOT NULL CHECK (event_time < TIME '24:00'),
    care_type TEXT NOT NULL CHECK (length(trim(care_type)) BETWEEN 1 AND 100),
    action TEXT NOT NULL CHECK (length(trim(action)) BETWEEN 1 AND 1000),
    observation TEXT NOT NULL CHECK (length(trim(observation)) BETWEEN 1 AND 1000),
    status TEXT NOT NULL CHECK (status IN ('PERFORMED', 'NOT_PERFORMED')),
    reason TEXT,
    follow_up TEXT,
    staff_user_id INTEGER NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (
        (status = 'PERFORMED' AND reason IS NULL AND follow_up IS NULL)
        OR (status = 'NOT_PERFORMED' AND reason IS NOT NULL AND follow_up IS NOT NULL
            AND length(trim(reason)) BETWEEN 1 AND 1000
            AND length(trim(follow_up)) BETWEEN 1 AND 1000)
    )
);

CREATE INDEX IF NOT EXISTS booking_care_events_chronology
    ON booking_care_events (booking_id, care_date, event_time, event_id);

CREATE TABLE IF NOT EXISTS booking_care_corrections (
    correction_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id INTEGER NOT NULL REFERENCES bookings(booking_id) ON DELETE RESTRICT,
    care_date DATE NOT NULL,
    kind TEXT NOT NULL CHECK (kind IN ('REPORT', 'EVENT')),
    record_id INTEGER NOT NULL,
    before_values JSONB NOT NULL,
    editor_user_id INTEGER NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
    edited_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS booking_care_corrections_history
    ON booking_care_corrections (booking_id, correction_id);
