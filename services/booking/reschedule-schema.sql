-- Booking applies this additive migration on startup for new and existing databases.
CREATE TABLE IF NOT EXISTS reschedule_requests (
    reschedule_request_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id INTEGER NOT NULL REFERENCES bookings(booking_id) ON DELETE RESTRICT,
    original_check_in DATE NOT NULL,
    original_check_out DATE NOT NULL,
    requested_check_in DATE NOT NULL,
    requested_check_out DATE NOT NULL,
    reason TEXT NOT NULL CHECK (length(trim(reason)) BETWEEN 1 AND 1000),
    status VARCHAR(10) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'APPROVED', 'DECLINED')),
    requested_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reviewed_by INTEGER REFERENCES users(user_id) ON DELETE RESTRICT,
    reviewed_at TIMESTAMPTZ,
    review_notes TEXT,
    CHECK (original_check_out > original_check_in AND requested_check_in <> original_check_in),
    CHECK (requested_check_out - requested_check_in = original_check_out - original_check_in),
    CHECK (
        (status = 'PENDING' AND reviewed_by IS NULL AND reviewed_at IS NULL)
        OR (status IN ('APPROVED', 'DECLINED') AND reviewed_by IS NOT NULL AND reviewed_at IS NOT NULL)
    )
);

CREATE INDEX IF NOT EXISTS reschedule_requests_booking_history ON reschedule_requests (booking_id, reschedule_request_id DESC);
CREATE UNIQUE INDEX IF NOT EXISTS reschedule_requests_one_pending ON reschedule_requests (booking_id) WHERE status = 'PENDING';
